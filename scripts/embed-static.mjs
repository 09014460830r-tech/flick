// Bundles the built SPA (dist/) into a module the Worker serves directly, so a deploy
// is a single script upload with no separate static-asset upload step.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".webmanifest": "application/manifest+json",
};

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });

const files = {};
for (const path of walk("dist")) {
  const ext = path.slice(path.lastIndexOf("."));
  if (!TYPES[ext]) throw new Error(`no content type for ${path}`);
  files[`/${relative("dist", path)}`] = { type: TYPES[ext], body: readFileSync(path, "utf8") };
}

writeFileSync(
  "src/worker/static.gen.ts",
  `// Generated by scripts/embed-static.mjs — do not edit.\nexport const STATIC: Record<string, { type: string; body: string }> = ${JSON.stringify(files)};\n`,
);
console.log(`embedded ${Object.keys(files).length} files`);
